# game_cast::update(flag) — seg1224:0FBD. Cast obj: +0 count byte, +2 items.
#   flag==0: ego->erase() + erase each ed_list actor
#   flag!=0: clear +0x52 bits 0x10|0x04 on each ed_list actor
#   _ed_list_size = 0
#   for i < count: if items[i]+0x52 & 1 -> remove(i)   (i++ still runs —
#     consecutive dead actors are SKIPPED: remove shifts list left)
#   cycle+move all actors: (count>>4)x16 unrolled + remainder
#   ego->draw() + draw each (new) ed_list actor
# remove(i): ~m_actor(3) [frees block at item seg], my_movsd shift, count--
# Globals: _ego@34A8, _ed_list@366A, _ed_list_size@37FA
# ---------------------------------------------------------------------------

# cast @0xB00; actors @0x0C00+i*0x60 (outside heap block); ego@0x1300
def _up_actor(off, x=2000, y=2000, xs=0, ys=0, flags=0, cycler=0):
    return [(SCR, off + 0x00, x), (SCR, off + 0x02, y),
            (SCR, off + 0x04, x + 8), (SCR, off + 0x06, y + 8),
            (SCR, off + 0x08, x + 4), (SCR, off + 0x0A, y + 4),
            (SCR, off + 0x10, 8), (SCR, off + 0x12, 8),
            (SCR, off + 0x14, xs & 0xFFFF), (SCR, off + 0x16, ys & 0xFFFF),
            (SCR, off + 0x18, 0), (SCR, off + 0x1A, 1), (SCR, off + 0x1C, 1),
            (SCR, off + 0x22, 0), (SCR, off + 0x34, 0),
            (SCR, off + 0x38, cycler), (SCR, off + 0x39, 0),
            (SCR, off + 0x3A, 1), (SCR, off + 0x3B, 2), (SCR, off + 0x3C, 0),
            (SCR, off + 0x3D, 0),
            (SCR, off + 0x46, 0x0500), (SCR, off + 0x48, SCR),
            (SCR, off + 0x52, flags)]

def _cast(cnt, offs):
    p = [(SCR, 0x0B00, cnt)]
    for i, o in enumerate(offs):
        p += [(SCR, 0x0B02 + i * 4, o), (SCR, 0x0B04 + i * 4, SCR)]
    return p

