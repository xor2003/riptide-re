# do_missle(act) — per-frame missile update. seg0b2c:352C.
#
# Branches:
#   !in_window -> dead (no explosion)
#   face==1: x_step -= 2 while > -max_speed; face==0: x_step += 2 while < max
#   +0x3D==3 (type9): y_step++ until 10
#   +0x52 bit7: random(10)==0 -> add_bubble
#   owner(+0x2C)+0x35 & 0x10 (player-owned):
#       scan _shootable_list[0.._shootable_count): skip dead(bit5),
#       touching -> target+0x52|=8, +0x28 += energy(+0x26), +0x1E=+-5 knockback,
#       +0x35 bit5 target: +0x52|=0x40 when hit within h/2 vertically,
#       energy<10 -> dead else pierce;
#       +0x34=='c' (top): tile[+0x18]==0x100 -> dead; else y_step-- toward -max
#   else (enemy-owned):
#       _smart_missiles==1 && +0x34!=0x63: y_step = sign(cur_sub.cy - act.cy)
#       scan _barrier_list: touching -> dead
