def main():
    verbose = "-v" in sys.argv
    run_all = "--all" in sys.argv          # ignore proven registry, run everything
    only = [a for a in sys.argv[1:] if a not in ("-v", "--all")]
    proven_names = set() if run_all else load_proven_names()
    proven_linears = set() if run_all else load_proven_linears()
    proven_exe = {} if run_all else load_proven_exe()
    npass = nfail = nproven = 0
    for t in TESTS:
        if only and not any(o in t.name for o in only):
            continue
        hits = _orig_names_for_test(t) & proven_names
        linear = _orig_linear_for_test(t)
        hit_linear = linear is not None and linear in proven_linears
        if hits or hit_linear:
            if hit_linear and not _proven_still_valid(linear, proven_exe):
                print(f"STALE {t.name}: z3 proof exists but machine code changed — retesting")
            else:
                nproven += 1
                if verbose:
                    label = sorted(hits)[0] if hits else f"linear 0x{linear:05x}"
                    print(f"PROVEN {t.name}: z3-verified ({label})")
                continue
        try:
            ok = run_test(t, verbose)
        except KeyError as e:
            print(f"SKIP {t.name}: unresolved {e}")
            continue
        npass += bool(ok)
        nfail += not ok
    print(f"\n{npass} pass/warn, {nfail} diff, {nproven} z3-proven skipped")


if __name__ == "__main__":
    main()
